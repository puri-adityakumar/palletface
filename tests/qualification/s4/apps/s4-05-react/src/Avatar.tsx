import { useMemo } from 'react'
import { ditherFace, type StyleSlug } from 'dither-face'

export interface AvatarProps {
  seed: string
  name?: string
  size?: number
  style?: StyleSlug
  inline?: boolean
  testId?: string
  alt?: string
}

/**
 * React consumer specimen: a typed <img> whose src is the recommended SVG
 * data URL, plus an optional inline rendering of the same generated SVG.
 */
export function Avatar({
  seed,
  name,
  size = 80,
  style = 'pixel-sprite',
  inline = false,
  testId,
  alt,
}: AvatarProps) {
  const svg = useMemo(() => {
    const options: { style: StyleSlug; px: number; name?: string } = { style, px: size }
    if (name !== undefined) options.name = name
    return ditherFace(seed, options)
  }, [seed, name, size, style])
  const src = useMemo(() => `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`, [svg])

  if (inline) {
    return (
      <div
        data-testid={testId}
        data-mode="inline"
        data-style={style}
        className="avatar-inline"
        // The SVG is generated by the library from React state, not arbitrary
        // user-supplied markup; the API documentation recommends keeping
        // untrusted HTML away from this output.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
    )
  }

  return (
    <img
      data-testid={testId}
      data-mode="img"
      data-style={style}
      src={src}
      width={size}
      height={size}
      alt={alt ?? `${style} avatar for ${name ?? seed}`}
    />
  )
}
